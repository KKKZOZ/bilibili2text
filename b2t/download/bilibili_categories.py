def get_bilibili_tname(tid: int) -> str:
    """Return the local partition name for a tid, or an empty string."""
    return BILIBILI_TID_TO_TNAME.get(tid, "")


def get_bilibili_parent_tid(tid: int) -> int:
    """Return the explicit parent tid, or 0 for a root/unknown partition."""
    return BILIBILI_TID_TO_PARENT_TID.get(tid, 0)


def get_bilibili_parent_tname(tid: int) -> str:
    """Return the local parent partition name, or an empty string."""
    return get_bilibili_tname(get_bilibili_parent_tid(tid))


def get_bilibili_category_filter_tids(tid: int) -> tuple[int, ...]:
    """Expand a root partition to itself and all of its direct children."""
    if tid <= 0:
        return ()
    child_tids = sorted(
        child_tid
        for child_tid, parent_tid in BILIBILI_TID_TO_PARENT_TID.items()
        if parent_tid == tid
    )
    return (tid, *child_tids)


